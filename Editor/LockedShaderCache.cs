using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using UnityEditor;
using UnityEngine;
using Thry.ThryEditor.Helpers;

namespace Thry.ThryEditor
{
    /// <summary>
    /// Content-addressed store for the shaders the ShaderOptimizer generates.
    ///
    /// By default a locked shader is written to an OptimizedShaders folder next to its material, so
    /// exporting a folder carries its locked shaders along. Inside it, shaders are filed under a hash of
    /// everything that affects the generated source, so materials in the same folder that hash the same
    /// share one. Once unlocking leaves a shader without users it is parked in CacheRoot rather than
    /// deleted, so the folder exports without it, and locking that folder's material with the same
    /// settings again moves it back instead of regenerating it.
    ///
    /// With Config.useGlobalLockedShaderCache on, every material locks into CacheRoot and shares it
    /// project-wide. Materials outside Assets and the flattened copies made for an upload always do.
    /// Shaders in CacheRoot are kept after unlocking and trimmed by the garbage collector.
    /// </summary>
    public static class LockedShaderCache
    {
        public const string CacheRoot = "Assets/_LockedShaderCache";
        public const string FolderName = "OptimizedShaders";
        public const string LockedShaderPrefix = "Hidden/Locked/";
        internal const string UploadMaterialsFolder = "Assets/__ThryUploadMaterials";
        const string SidecarName = ".thrylock";

        const string ReadmeName = "README.txt";
        const string ReadmeContents =
@"This folder holds the optimized shader cache generated by the ShaderOptimizer. If you
are using Poiyomi Shaders, this folder is very important!

- Everything in here is generated. Don't hand-edit it, or your changes will be overwritten.
- By default, locked materials keep their shaders in an OptimizedShaders folder next to them. When you unlock a material, its shader is moved here instead of being deleted, so locking it again with the same settings is instant.
- With 'Global Locked Shader Cache' turned on in ThryEditor Settings, every locked material keeps its shader in here instead. DO NOT DELETE THIS FOLDER in that case! Locked materials would lose their shaders and get unlocked.
- Each subfolder is named after a shader, and each folder inside that is one unique combination of material settings. Materials with identical settings share a single shader on purpose, which allows improved performance on Lock and Unlock.
- VERSION CONTROL: This folder can be safely ignored via .gitignore while 'Global Locked Shader Cache' is off.
- To clear this Cache: Poi > Thry > ThryEditor > Optimized Shader Cache > Remove Unused.
";

        #region Naming and Paths

        /// <summary>The folder a material's locked shaders are written to.</summary>
        public static string GetRoot(Material material)
        {
            return GetRoot(AssetDatabase.GetAssetPath(material));
        }

        public static string GetRoot(string materialPath)
        {
            materialPath = (materialPath ?? string.Empty).Replace('\\', '/');
            if (Config.Instance.useGlobalLockedShaderCache || !materialPath.StartsWith("Assets/", StringComparison.OrdinalIgnoreCase))
                return CacheRoot;
            // Flattened variant copies are deleted after the upload. Their shaders stay cached for the next one.
            if (materialPath.StartsWith(UploadMaterialsFolder + "/", StringComparison.OrdinalIgnoreCase))
                return CacheRoot;
            return Path.GetDirectoryName(materialPath).Replace('\\', '/') + "/" + FolderName;
        }

        /// <summary>
        /// Name of the locked shader for a given root, original shader name and content hash. Folders
        /// can hold the same hash, so outside CacheRoot the name also carries the folder's GUID.
        /// </summary>
        public static string GetLockedShaderName(string root, string originalShaderName, string hash)
        {
            string name = LockedShaderPrefix + originalShaderName + "/" + hash;
            return root.Equals(CacheRoot, StringComparison.OrdinalIgnoreCase) ? name : name + "/" + GetFolderKey(root);
        }

        static string GetFolderKey(string root)
        {
            string owner = Path.GetDirectoryName(root).Replace('\\', '/');
            string guid = AssetDatabase.AssetPathToGUID(owner);
            if (string.IsNullOrEmpty(guid))
            {
                using (var md5 = System.Security.Cryptography.MD5.Create())
                    guid = BitConverter.ToString(md5.ComputeHash(Encoding.UTF8.GetBytes(owner))).Replace("-", "").ToLowerInvariant();
            }
            return guid.Substring(0, 8);
        }

        /// <summary>Folder holding one locked shader.</summary>
        public static string GetEntryDirectory(string root, string originalShaderName, string hash)
        {
            return root + "/" + SanitizeFolderName(originalShaderName) + "/" + hash;
        }

        /// <summary>Path of the locked copy of <paramref name="originalShader"/> inside an entry.</summary>
        public static string GetShaderPath(string entryDirectory, Shader originalShader)
        {
            return entryDirectory + "/" + Path.GetFileName(AssetDatabase.GetAssetPath(originalShader));
        }

        /// <summary>True if the given asset path lives inside CacheRoot, whose shaders outlive unlocking.</summary>
        public static bool IsInCache(string assetPath)
        {
            return !string.IsNullOrEmpty(assetPath) && assetPath.Replace('\\', '/').StartsWith(CacheRoot + "/", StringComparison.OrdinalIgnoreCase);
        }

        /// <summary>True if the given asset path is inside an entry of an OptimizedShaders folder.</summary>
        public static bool IsFolderEntry(string assetPath)
        {
            return GetOwnerFolder(assetPath) != null;
        }

        /// <summary>True for anything the optimizer generated, in CacheRoot or next to a material.</summary>
        public static bool IsGenerated(string assetPath)
        {
            return IsInCache(assetPath) || IsFolderEntry(assetPath);
        }

        /// <summary>
        /// The folder whose materials an OptimizedShaders entry belongs to, or null when the path is not
        /// inside one. Shaders from before the cache sit one level higher, in a folder named after their
        /// material, and are not entries.
        /// </summary>
        public static string GetOwnerFolder(string assetPath)
        {
            if (string.IsNullOrEmpty(assetPath)) return null;
            string[] parts = assetPath.Replace('\\', '/').Split('/');
            for (int i = parts.Length - 3; i >= 1; i--)
            {
                if (parts[i] == FolderName && IsHash(parts[i + 2]))
                    return string.Join("/", parts, 0, i);
            }
            return null;
        }

        /// <summary>
        /// Where a folder entry is parked once nothing uses it: CacheRoot/&lt;shader&gt;/&lt;hash&gt;-&lt;folder key&gt;.
        /// The key keeps entries of different folders apart, since each one's shader name carries it.
        /// </summary>
        static string GetParkedEntryDirectory(string folderEntryDirectory)
        {
            string shaderDirectory = Path.GetDirectoryName(folderEntryDirectory).Replace('\\', '/');
            string root = Path.GetDirectoryName(shaderDirectory).Replace('\\', '/');
            return CacheRoot + "/" + Path.GetFileName(shaderDirectory) + "/" + Path.GetFileName(folderEntryDirectory) + "-" + GetFolderKey(root);
        }

        /// <summary>True for an entry folder name that is a plain settings hash, which a parked entry's is not.</summary>
        internal static bool IsHash(string name)
        {
            if (name.Length != 32) return false;
            foreach (char c in name)
                if (!(c >= '0' && c <= '9' || c >= 'a' && c <= 'f')) return false;
            return true;
        }

        /// <summary>
        /// Turns a shader name into one path segment. Shader names carry '/' and often a leading '.'
        /// (".poiyomi/Poiyomi Pro"), and Unity ignores folders that start with '.' or end with '~',
        /// so neither can survive into a folder name.
        /// </summary>
        public static string SanitizeFolderName(string shaderName)
        {
            if (string.IsNullOrEmpty(shaderName)) return "Unnamed";

            // Windows' invalid chars, since the cache can be exported there
            StringBuilder sb = new StringBuilder(shaderName.Length);
            foreach (char c in shaderName)
            {
                if (c < ' ' || "\\/:*?\"<>|".IndexOf(c) >= 0) sb.Append('_');
                else sb.Append(c);
            }

            // Unity skips folders starting with '.' and ending with '~'; Windows rejects names that
            // end in '.' or ' '.
            string result = sb.ToString().TrimStart('.').TrimEnd('~', '.', ' ');
            return string.IsNullOrEmpty(result) ? "Unnamed" : result;
        }

        #endregion

        #region Lookup

        /// <summary>
        /// Finds an already-generated locked shader in an entry. Only sees shaders the AssetDatabase has
        /// imported, so callers still need their own book-keeping for shaders written earlier in the
        /// same StartAssetEditing block. Looked up by path rather than name: a duplicated folder holds
        /// copies with the same names.
        /// </summary>
        public static bool TryGetCachedShader(string entryDirectory, Shader originalShader, out Shader shader)
        {
            shader = null;

            // Developer mode edits shader and include sources constantly, and the hash cannot see
            // changes inside included files. Never reuse in that case.
            if (Config.Instance.enableDeveloperMode) return false;

            Shader found = AssetDatabase.LoadAssetAtPath<Shader>(GetShaderPath(entryDirectory, originalShader));
            if (found == null || found.IsBroken()) return false;

            // A cached shader that failed to compile is worse than no cached shader.
            if (ShaderUtil.ShaderHasError(found)) return false;

            shader = found;
            return true;
        }

        #endregion

        #region Parking

        /// <summary>
        /// Moves a folder entry that no material uses any more into CacheRoot instead of deleting it. The
        /// folder then exports without it, and locking one of its materials with the same settings again
        /// moves it back (see TryRestoreParkedEntry). Must run outside StartAssetEditing, since it moves
        /// assets. Returns true when the shader was kept in CacheRoot. When the move fails the entry is
        /// left where it was.
        /// </summary>
        public static bool ParkEntry(string entryDirectory)
        {
            if (!IsFolderEntry(entryDirectory) || !Directory.Exists(entryDirectory)) return false;

            string parked = GetParkedEntryDirectory(entryDirectory);
            // Read first: the sidecar is a dot file, which the AssetDatabase does not know about
            EntryInfo info = ReadEntry(entryDirectory) ?? new EntryInfo();
            s_rootsToPrune.Add(Path.GetDirectoryName(Path.GetDirectoryName(entryDirectory)).Replace('\\', '/'));

            // An older copy under the same name is parked already. The one that was just in use replaces it,
            // so two shaders never share the name.
            if (Directory.Exists(parked) && !DeleteCollected(parked))
            {
                ThryLogger.LogWarn("Could not replace the cached locked shader " + parked + ", so the unused " + entryDirectory + " stays where it is.");
                return false;
            }

            EnsureCacheRoot();
            if (!EnsureAssetFolder(Path.GetDirectoryName(parked).Replace('\\', '/')))
            {
                ThryLogger.LogWarn("Could not create " + Path.GetDirectoryName(parked) + " to keep the unused locked shader " + entryDirectory + " in.");
                return false;
            }

            string error = AssetDatabase.MoveAsset(entryDirectory, parked);
            if (!string.IsNullOrEmpty(error))
            {
                ThryLogger.LogWarn("Could not move the unused locked shader " + entryDirectory + " to " + parked + ": " + error);
                return false;
            }

            try
            {
                string oldSidecar = GetSidecarPath(entryDirectory);
                if (File.Exists(oldSidecar)) File.Delete(oldSidecar);
                if (Directory.Exists(entryDirectory) && Directory.GetFileSystemEntries(entryDirectory).Length == 0) Directory.Delete(entryDirectory);
            }
            catch (IOException) { }

            info.UserGuids.Clear();
            WriteEntry(parked, info);
            Touch(parked);
            return true;
        }

        /// <summary>
        /// Moves a parked copy of a folder entry back beside the folder's materials, when one is parked
        /// under the same shader name. Runs inside the lock's StartAssetEditing block, so the files are
        /// moved on disk along with their .meta files, keeping their GUIDs, and the AssetDatabase picks
        /// the move up at the batch's refresh. Returns true once the entry is back in place.
        ///
        /// Only an exact match comes back. Its folder is named after the settings hash, which covers every
        /// material value the generated code depends on, the original shader and the files it inlines, the
        /// optimizer version and the color space. A material whose options changed hashes differently and
        /// gets a newly generated shader instead.
        /// </summary>
        public static bool TryRestoreParkedEntry(string entryDirectory, Shader originalShader, string lockedShaderName)
        {
            // Developer mode edits sources the hash can't see. Never reuse there, as TryGetCachedShader.
            if (Config.Instance.enableDeveloperMode) return false;
            // Never overwrite what is in the folder already, even a broken entry: generating replaces that
            if (!IsFolderEntry(entryDirectory) || Directory.Exists(entryDirectory)) return false;

            string parked = GetParkedEntryDirectory(entryDirectory);
            if (!Directory.Exists(parked)) return false;

            Shader shader = AssetDatabase.LoadAssetAtPath<Shader>(GetShaderPath(parked, originalShader));
            // Unusable: missing, failing to compile, or without the stripped texture list the material needs
            // to be locked onto it. Its name would also clash with the shader generated in its place.
            if (shader == null || shader.IsBroken() || ShaderUtil.ShaderHasError(shader) || ReadEntry(parked) == null)
            {
                DeleteEntry(parked);
                return false;
            }
            // A copy of a duplicated folder still carries the other folder's name
            if (shader.name != lockedShaderName) return false;

            try
            {
                Directory.CreateDirectory(Path.GetDirectoryName(entryDirectory));
                // Recovery would otherwise take the shader leaving CacheRoot for a lost one
                MarkCollected(parked);
                Directory.Move(parked, entryDirectory);
                if (File.Exists(parked + ".meta")) File.Move(parked + ".meta", entryDirectory + ".meta");
            }
            catch (Exception e) when (e is IOException || e is UnauthorizedAccessException)
            {
                ThryLogger.LogWarn("Could not move the cached locked shader " + parked + " back to " + entryDirectory + ": " + e.Message);
                return Directory.Exists(entryDirectory) && File.Exists(GetShaderPath(entryDirectory, originalShader));
            }

            Touch(entryDirectory);
            return true;
        }

        /// <summary>
        /// Makes a folder known to the AssetDatabase, creating it if needed. A folder that is on disk but
        /// not imported yet is imported, since CreateFolder would make a "Folder 1" next to it.
        /// </summary>
        static bool EnsureAssetFolder(string folder)
        {
            if (AssetDatabase.IsValidFolder(folder)) return true;
            string parent = Path.GetDirectoryName(folder).Replace('\\', '/');
            if (string.IsNullOrEmpty(parent) || !EnsureAssetFolder(parent)) return false;
            if (Directory.Exists(folder)) AssetDatabase.ImportAsset(folder, ImportAssetOptions.ForceSynchronousImport);
            else AssetDatabase.CreateFolder(parent, Path.GetFileName(folder));
            return AssetDatabase.IsValidFolder(folder);
        }

        #endregion

        #region Sidecar

        /// <summary>Per-entry book-keeping that has to outlive the editor session.</summary>
        public class EntryInfo
        {
            /// <summary>Texture properties the optimizer removed, so unlock can restore them.</summary>
            public List<string> StrippedTextures = new List<string>();

            /// <summary>GUIDs of the materials known to use this entry. Drives the shared-shader tag.</summary>
            public List<string> UserGuids = new List<string>();

            /// <summary>Hash of the generated text with the shader's own name masked, so materials whose
            /// settings hash differently but generate the same code can share the entry.</summary>
            public string ContentHash;
        }

        static string GetSidecarPath(string entryDirectory)
        {
            return entryDirectory + "/" + SidecarName;
        }

        /// <summary>Reads an entry's sidecar. Returns null when it is missing or unreadable.</summary>
        public static EntryInfo ReadEntry(string entryDirectory)
        {
            string path = GetSidecarPath(entryDirectory);
            if (!File.Exists(path)) return null;

            try
            {
                EntryInfo info = new EntryInfo();
                foreach (string raw in File.ReadAllLines(path))
                {
                    string line = raw.Trim();
                    if (line.Length == 0) continue;

                    if (line.StartsWith("strip ", StringComparison.Ordinal))
                        info.StrippedTextures.Add(line.Substring(6));
                    else if (line.StartsWith("user ", StringComparison.Ordinal))
                        info.UserGuids.Add(line.Substring(5));
                    else if (line.StartsWith("content ", StringComparison.Ordinal))
                        info.ContentHash = line.Substring(8);
                }
                return info;
            }
            catch (IOException e)
            {
                ThryLogger.LogWarn("Could not read locked shader cache entry " + path + ": " + e.Message);
                return null;
            }
        }

        public static void WriteEntry(string entryDirectory, EntryInfo info)
        {
            if (info == null) return;

            try
            {
                Directory.CreateDirectory(entryDirectory);

                StringBuilder sb = new StringBuilder();
                sb.AppendLine("# Generated by the Thry Shader Optimizer. Safe to delete.");
                foreach (string tex in info.StrippedTextures.Distinct())
                    sb.Append("strip ").AppendLine(tex);
                foreach (string guid in info.UserGuids.Where(g => !string.IsNullOrEmpty(g)).Distinct())
                    sb.Append("user ").AppendLine(guid);
                if (!string.IsNullOrEmpty(info.ContentHash))
                    sb.Append("content ").AppendLine(info.ContentHash);

                File.WriteAllText(GetSidecarPath(entryDirectory), sb.ToString());
            }
            catch (IOException e)
            {
                // Losing the sidecar costs a regeneration next time, nothing more.
                ThryLogger.LogWarn("Could not write locked shader cache entry for " + entryDirectory + ": " + e.Message);
            }
        }

        /// <summary>Adds a material to an entry's user list and marks the entry as recently used.</summary>
        public static void RegisterUser(string entryDirectory, string materialGuid)
        {
            EntryInfo info = ReadEntry(entryDirectory) ?? new EntryInfo();
            if (!string.IsNullOrEmpty(materialGuid) && !info.UserGuids.Contains(materialGuid))
                info.UserGuids.Add(materialGuid);
            WriteEntry(entryDirectory, info);
            Touch(entryDirectory);
        }

        /// <summary>Drops a material from an entry's user list. The shader itself is left for the GC.</summary>
        public static void DeregisterUser(string entryDirectory, string materialGuid)
        {
            EntryInfo info = ReadEntry(entryDirectory);
            if (info == null) return;
            if (info.UserGuids.Remove(materialGuid)) WriteEntry(entryDirectory, info);
        }

        /// <summary>Comma-joined GUID list for TAG_ALL_MATERIALS_GUIDS_USING_THIS_LOCKED_SHADER.</summary>
        public static string GetUserTag(string entryDirectory)
        {
            EntryInfo info = ReadEntry(entryDirectory);
            return info == null ? string.Empty : string.Join(",", info.UserGuids.ToArray());
        }

        /// <summary>Bumps the entry's mtime, which is what the GC uses as its least-recently-used clock.</summary>
        public static void Touch(string entryDirectory)
        {
            try
            {
                if (Directory.Exists(entryDirectory))
                    Directory.SetLastWriteTimeUtc(entryDirectory, DateTime.UtcNow);
            }
            catch (IOException)
            {
                // Recency is a heuristic; failing to record it is not worth surfacing.
            }
        }

        public static void EnsureCacheRoot()
        {
            try
            {
                Directory.CreateDirectory(CacheRoot);
                string readme = CacheRoot + "/" + ReadmeName;
                // Rewritten when outdated, since what the folder holds depends on the version
                if (!File.Exists(readme) || File.ReadAllText(readme) != ReadmeContents) File.WriteAllText(readme, ReadmeContents);
            }
            catch (IOException e)
            {
                ThryLogger.LogWarn("Could not create the optimized shader cache folder: " + e.Message);
            }
        }

        #endregion

        #region Garbage Collection

        /// <summary>
        /// Every entry folder, i.e. &lt;root&gt;/&lt;shader&gt;/&lt;hash&gt;. CacheRoot only, unless
        /// <paramref name="includeFolders"/> also searches Assets for OptimizedShaders folders.
        /// </summary>
        static List<string> GetAllEntryDirectories(bool includeFolders = false)
        {
            List<string> entries = new List<string>();
            List<string> roots = new List<string>();
            if (Directory.Exists(CacheRoot)) roots.Add(CacheRoot);
            if (includeFolders)
                roots.AddRange(Directory.GetDirectories("Assets", FolderName, SearchOption.AllDirectories).Select(d => d.Replace('\\', '/')));

            foreach (string root in roots)
            {
                foreach (string shaderDir in Directory.GetDirectories(root))
                {
                    foreach (string entryDir in Directory.GetDirectories(shaderDir))
                    {
                        string entry = entryDir.Replace('\\', '/');
                        if (root == CacheRoot || IsFolderEntry(entry)) entries.Add(entry);
                    }
                }
            }

            return entries;
        }

        static long GetDirectorySizeBytes(string directory)
        {
            long size = 0;
            try
            {
                foreach (string file in Directory.GetFiles(directory, "*", SearchOption.AllDirectories))
                    size += new FileInfo(file).Length;
            }
            catch (IOException)
            {
                // Treat an unreadable folder as empty rather than aborting the sweep.
            }
            return size;
        }

        /// <summary>
        /// Cache-relative asset paths that some material still points at. Uses the import database's
        /// dependency info rather than loading materials, which matters because a material on a large
        /// shader deserializes thousands of properties.
        /// </summary>
        static HashSet<string> GetReferencedCachePaths()
        {
            HashSet<string> referenced = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

            foreach (string guid in AssetDatabase.FindAssets("t:Material"))
            {
                string materialPath = AssetDatabase.GUIDToAssetPath(guid);
                if (string.IsNullOrEmpty(materialPath)) continue;

                foreach (string dependency in AssetDatabase.GetDependencies(materialPath, false))
                {
                    if (IsGenerated(dependency)) referenced.Add(dependency.Replace('\\', '/'));
                }
            }

            // Also count locks on loaded materials that aren't saved yet
            foreach (Material material in Resources.FindObjectsOfTypeAll<Material>())
            {
                if (material == null || material.shader == null) continue;
                string shaderPath = AssetDatabase.GetAssetPath(material.shader);
                if (IsGenerated(shaderPath)) referenced.Add(shaderPath.Replace('\\', '/'));
            }

            return referenced;
        }

        /// <summary>
        /// The .mat files under Assets by the shader GUID their header names. Reading the first kilobyte of each
        /// file takes a fraction of the time the import database needs for every material's dependencies.
        /// </summary>
        internal static Dictionary<string, List<string>> GetMaterialPathsByShaderGuid()
        {
            var materialsByShader = new Dictionary<string, List<string>>(StringComparer.Ordinal);
            byte[] buffer = new byte[1024];

            foreach (string guid in AssetDatabase.FindAssets("t:Material", new[] { "Assets" }))
            {
                string materialPath = AssetDatabase.GUIDToAssetPath(guid);
                if (!materialPath.EndsWith(".mat", StringComparison.OrdinalIgnoreCase)) continue;

                string head;
                try
                {
                    using (var stream = new FileStream(materialPath, FileMode.Open, FileAccess.Read, FileShare.ReadWrite, buffer.Length))
                        head = Encoding.UTF8.GetString(buffer, 0, stream.Read(buffer, 0, buffer.Length));
                }
                catch (IOException) { continue; }

                int shader = head.IndexOf("m_Shader:", StringComparison.Ordinal);
                int start = shader < 0 ? -1 : head.IndexOf("guid: ", shader, StringComparison.Ordinal);
                if (start < 0 || start + 38 > head.Length) continue;

                string shaderGuid = head.Substring(start + 6, 32);
                if (!materialsByShader.TryGetValue(shaderGuid, out List<string> paths))
                    materialsByShader[shaderGuid] = paths = new List<string>();
                paths.Add(materialPath);
            }

            return materialsByShader;
        }

        /// <summary>
        /// Deletes entries no material references. With <paramref name="budgetBytes"/> above zero
        /// it stops as soon as the cache fits the budget, oldest entry first; otherwise it removes every
        /// unreferenced entry. Returns the number of entries deleted.
        /// </summary>
        public static int CollectGarbage(long budgetBytes = 0, ICollection<string> protectedEntries = null, bool includeFolders = false)
        {
            List<string> entries = GetAllEntryDirectories(includeFolders);
            if (entries.Count == 0) return 0;

            HashSet<string> referenced = GetReferencedCachePaths();

            // An entry is live if any material references a file inside it. Entries the caller marks as
            // protected are kept regardless: the import database only knows what is saved to disk, so a
            // material locked moments ago still appears to reference its old shader.
            List<string> unreferenced = entries
                .Where(entry => !(protectedEntries != null && protectedEntries.Contains(entry)))
                .Where(entry => !referenced.Any(r => r.StartsWith(entry + "/", StringComparison.OrdinalIgnoreCase)))
                .ToList();

            if (unreferenced.Count == 0) return 0;

            long total = 0;
            if (budgetBytes > 0)
            {
                foreach (string entry in entries) total += GetDirectorySizeBytes(entry);
                if (total <= budgetBytes) return 0;

                // Least recently used goes first.
                unreferenced = unreferenced.OrderBy(e => Directory.GetLastWriteTimeUtc(e)).ToList();
            }

            int deleted = 0;
            foreach (string entry in unreferenced)
            {
                long entrySize = budgetBytes > 0 ? GetDirectorySizeBytes(entry) : 0;

                if (DeleteEntry(entry))
                {
                    deleted++;
                    total -= entrySize;
                }

                if (budgetBytes > 0 && total <= budgetBytes) break;
            }

            if (deleted > 0)
            {
                PruneEmptyFolders();
                ThryLogger.LogDetail("Removed " + deleted + " unused locked shader" + (deleted == 1 ? "" : "s") + ".");
            }

            return deleted;
        }

        // Roots that lost an entry. Their emptied folders are removed once asset editing has stopped.
        static readonly HashSet<string> s_rootsToPrune = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

        /// <summary>Deletes an entry. Call PruneEmptyFolders outside StartAssetEditing afterwards.</summary>
        public static bool DeleteEntry(string entryDirectory)
        {
            s_rootsToPrune.Add(Path.GetDirectoryName(Path.GetDirectoryName(entryDirectory)).Replace('\\', '/'));
            if (DeleteCollected(entryDirectory)) return true;
            ThryLogger.LogWarn("Could not delete unused locked shader " + entryDirectory);
            return false;
        }

        /// <summary>Removes shader folders, and OptimizedShaders folders, left empty by DeleteEntry.</summary>
        public static void PruneEmptyFolders()
        {
            foreach (string root in s_rootsToPrune)
            {
                if (!Directory.Exists(root)) continue;
                foreach (string shaderDir in Directory.GetDirectories(root))
                {
                    if (Directory.GetFileSystemEntries(shaderDir).Length == 0)
                        DeleteCollected(shaderDir.Replace('\\', '/'));
                }
                if (!root.Equals(CacheRoot, StringComparison.OrdinalIgnoreCase) && Directory.GetFileSystemEntries(root).Length == 0)
                    DeleteCollected(root);
            }
            s_rootsToPrune.Clear();
        }

        // Deleted or moved away by the optimizer itself, so recovery can skip them
        static readonly HashSet<string> s_collectedPaths = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

        internal static bool DeleteCollected(string assetPath)
        {
            MarkCollected(assetPath);
            if (!AssetDatabase.DeleteAsset(assetPath))
            {
                s_collectedPaths.Remove(assetPath);
                return false;
            }
            return true;
        }

        static void MarkCollected(string assetPath)
        {
            s_collectedPaths.Add(assetPath);
            // The postprocessor has seen the deletion by the next tick
            EditorApplication.delayCall -= ForgetCollected;
            EditorApplication.delayCall += ForgetCollected;
        }

        /// <summary>True if the GC deleted this asset, or the folder it was in.</summary>
        public static bool WasCollected(string assetPath)
        {
            if (s_collectedPaths.Count == 0 || string.IsNullOrEmpty(assetPath)) return false;
            assetPath = assetPath.Replace('\\', '/');
            foreach (string collected in s_collectedPaths)
            {
                if (assetPath.Equals(collected, StringComparison.OrdinalIgnoreCase)
                    || assetPath.StartsWith(collected + "/", StringComparison.OrdinalIgnoreCase))
                    return true;
            }
            return false;
        }

        public static void ForgetCollected()
        {
            s_collectedPaths.Clear();
        }

        /// <summary>
        /// Trims the cache when it grows past the configured budget. Called after a lock/unlock batch,
        /// so it must run outside StartAssetEditing.
        /// </summary>
        public static void CollectGarbageIfOverBudget(ICollection<string> protectedEntries = null)
        {
            int budgetMB = Config.Instance.lockedShaderCacheBudgetMB;
            if (budgetMB <= 0) return; // 0 disables trimming entirely

            long budgetBytes = (long)budgetMB * 1024L * 1024L;

            // Cheap pre-check so the common case never pays for the material sweep.
            long total = 0;
            foreach (string entry in GetAllEntryDirectories())
            {
                total += GetDirectorySizeBytes(entry);
                if (total > budgetBytes) break;
            }
            if (total <= budgetBytes) return;

            CollectGarbage(budgetBytes, protectedEntries);
        }

        /// <summary>Total bytes on disk, and how many locked shaders that covers, in CacheRoot and every OptimizedShaders folder.</summary>
        public static void GetCacheStats(out long sizeBytes, out int entryCount)
        {
            sizeBytes = 0;
            List<string> entries = GetAllEntryDirectories(includeFolders: true);
            entryCount = entries.Count;
            foreach (string entry in entries)
                sizeBytes += GetDirectorySizeBytes(entry);
        }

        /// <summary>
        /// Moves shaders that materials in Assets locked into CacheRoot to OptimizedShaders folders
        /// beside those materials. An entry shared across folders is copied into each one under a new
        /// name, and the materials there are switched to their copy. Returns how many entries moved.
        /// </summary>
        public static int MoveEntriesBesideMaterials()
        {
            if (GetAllEntryDirectories().Count == 0)
            {
                RemoveEmptyCacheRoot();
                return 0;
            }

            // Entries a material in Assets still uses after this run. They are tried again next session.
            HashSet<string> unmoved = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

            // Locked shader path -> material paths using it, from the import database
            Dictionary<string, List<string>> users = new Dictionary<string, List<string>>(StringComparer.OrdinalIgnoreCase);
            foreach (string guid in AssetDatabase.FindAssets("t:Material"))
            {
                string materialPath = AssetDatabase.GUIDToAssetPath(guid);
                if (string.IsNullOrEmpty(materialPath)) continue;
                foreach (string dependency in AssetDatabase.GetDependencies(materialPath, false))
                {
                    if (!IsInCache(dependency) || !dependency.EndsWith(".shader", StringComparison.OrdinalIgnoreCase)) continue;
                    if (!users.TryGetValue(dependency, out List<string> list)) users[dependency] = list = new List<string>();
                    if (!list.Contains(materialPath)) list.Add(materialPath);
                }
            }

            int moved = 0;
            foreach (KeyValuePair<string, List<string>> pair in users)
            {
                string shaderPath = pair.Key;
                string entry = Path.GetDirectoryName(shaderPath).Replace('\\', '/');
                EntryInfo info = ReadEntry(entry) ?? new EntryInfo();
                Shader shader = AssetDatabase.LoadAssetAtPath<Shader>(shaderPath);
                if (shader == null)
                {
                    unmoved.Add(entry);
                    continue;
                }

                bool entryMoved = false;
                foreach (IGrouping<string, string> group in pair.Value.GroupBy(p => GetRoot(p), StringComparer.OrdinalIgnoreCase))
                {
                    string root = group.Key;
                    if (root.Equals(CacheRoot, StringComparison.OrdinalIgnoreCase)) continue;

                    // A parked entry's folder name also carries its folder key, which an OptimizedShaders entry's must not
                    string hash = Path.GetFileName(entry).Split('-')[0];
                    string target = root + "/" + Path.GetFileName(Path.GetDirectoryName(entry)) + "/" + hash;
                    string targetShaderPath = target + "/" + Path.GetFileName(shaderPath);
                    EntryInfo targetInfo = new EntryInfo { ContentHash = info.ContentHash };
                    targetInfo.StrippedTextures.AddRange(info.StrippedTextures);
                    targetInfo.UserGuids.AddRange(group.Select(AssetDatabase.AssetPathToGUID));

                    if (!entryMoved && !Directory.Exists(target))
                    {
                        if (!EnsureAssetFolder(Path.GetDirectoryName(target).Replace('\\', '/')))
                        {
                            unmoved.Add(entry);
                            continue;
                        }
                        string error = AssetDatabase.MoveAsset(entry, target);
                        if (!string.IsNullOrEmpty(error))
                        {
                            ThryLogger.LogWarn("Could not move locked shader " + entry + " to " + target + ": " + error);
                            unmoved.Add(entry);
                            continue;
                        }
                        entryMoved = true;
                        entry = target;
                        shaderPath = targetShaderPath;
                        WriteEntry(target, targetInfo);
                        moved++;
                        continue;
                    }

                    // Each folder's copy needs a name of its own
                    if (!Directory.Exists(target)) CopyEntry(entry, target, shader.name, shader.name + "/" + GetFolderKey(root));
                    Shader copy = AssetDatabase.LoadAssetAtPath<Shader>(targetShaderPath);
                    if (copy == null || copy.IsBroken())
                    {
                        ThryLogger.LogWarn("Could not copy locked shader " + shaderPath + " to " + target);
                        if (IsInCache(entry)) unmoved.Add(entry);
                        continue;
                    }
                    EntryInfo existing = ReadEntry(target);
                    if (existing != null) targetInfo.UserGuids.AddRange(existing.UserGuids.Except(targetInfo.UserGuids));
                    WriteEntry(target, targetInfo);

                    string tag = string.Join(",", targetInfo.UserGuids);
                    foreach (string materialPath in group)
                    {
                        Material material = AssetDatabase.LoadAssetAtPath<Material>(materialPath);
                        if (material == null || material.shader != shader) continue;
                        ShaderOptimizer.SwapLockedShader(material, copy);
                        material.SetOverrideTag(ShaderOptimizer.TAG_ALL_MATERIALS_GUIDS_USING_THIS_LOCKED_SHADER, tag);
                        AssetDatabase.SaveAssetIfDirty(material);
                    }
                    moved++;
                }
            }

            // Whatever is left in CacheRoot is used by nothing, or only by materials outside Assets. Unused
            // shaders stay cached for a later lock and are trimmed once the cache outgrows its budget.

            // What stays belongs to materials outside Assets, so it must not ask for this move again
            foreach (string left in GetAllEntryDirectories())
            {
                if (unmoved.Contains(left)) continue;
                EntryInfo leftInfo = ReadEntry(left);
                if (leftInfo != null && leftInfo.UserGuids.RemoveAll(IsAssetsMaterial) == 0) continue;
                WriteEntry(left, leftInfo ?? new EntryInfo());
            }
            RemoveEmptyCacheRoot();

            if (moved > 0)
                ThryLogger.Log("Moved " + moved + " locked shader" + (moved == 1 ? "" : "s") + " from " + CacheRoot + " to OptimizedShaders folders next to their materials.");
            return moved;
        }

        /// <summary>
        /// True when CacheRoot holds an entry a material in Assets may use: one whose sidecar lists such a
        /// material, or one that arrived without a sidecar. Entries of materials outside Assets stay there.
        /// </summary>
        internal static bool HasEntriesToMove()
        {
            foreach (string entry in GetAllEntryDirectories())
            {
                EntryInfo info = ReadEntry(entry);
                if (info == null || info.UserGuids.Any(IsAssetsMaterial)) return true;
            }
            return false;
        }

        static bool IsAssetsMaterial(string guid)
        {
            string path = AssetDatabase.GUIDToAssetPath(guid);
            return path.StartsWith("Assets/", StringComparison.OrdinalIgnoreCase) && !IsInCache(path)
                && !path.StartsWith(UploadMaterialsFolder + "/", StringComparison.OrdinalIgnoreCase);
        }

        static void RemoveEmptyCacheRoot()
        {
            if (!Directory.Exists(CacheRoot)) return;
            s_rootsToPrune.Add(CacheRoot);
            PruneEmptyFolders();
            if (Directory.GetDirectories(CacheRoot).Length == 0) DeleteCollected(CacheRoot);
        }

        static void CopyEntry(string source, string target, string oldName, string newName)
        {
            EnsureAssetFolder(target);
            foreach (string file in Directory.GetFiles(source))
            {
                string fileName = Path.GetFileName(file);
                if (fileName == SidecarName || fileName.EndsWith(".meta", StringComparison.OrdinalIgnoreCase)) continue;
                string text = File.ReadAllText(file);
                if (fileName.EndsWith(".shader", StringComparison.OrdinalIgnoreCase))
                    text = text.Replace("\"" + oldName + "\"", "\"" + newName + "\"");
                File.WriteAllText(target + "/" + fileName, text);
            }
            AssetDatabase.ImportAsset(target, ImportAssetOptions.ImportRecursive | ImportAssetOptions.ForceSynchronousImport);
        }

        /// <summary>Deletes every locked shader. The caller must run LockedShaderRecovery.</summary>
        public static void Clear()
        {
            foreach (string entry in GetAllEntryDirectories(includeFolders: true))
                DeleteEntry(entry);
            PruneEmptyFolders();
        }

        #endregion
    }

    /// <summary>
    /// While the global cache is off, moves the shaders materials in Assets are locked to out of CacheRoot
    /// and next to those materials: once per session, and again whenever the global cache is turned off.
    /// </summary>
    static class LockedShaderCacheMove
    {
        const string SessionKey = "Thry.LockedShaderCache.MovedBesideMaterials";

        [InitializeOnLoadMethod]
        static void Schedule()
        {
            if (SessionState.GetBool(SessionKey, false) || !Directory.Exists(LockedShaderCache.CacheRoot)) return;
            EditorApplication.delayCall += Run;
        }

        /// <summary>Called by the settings window once Config.useGlobalLockedShaderCache has changed.</summary>
        internal static void OnGlobalCacheSettingChanged()
        {
            if (Config.Instance.useGlobalLockedShaderCache || !Directory.Exists(LockedShaderCache.CacheRoot)) return;
            EditorApplication.delayCall -= Run;
            EditorApplication.delayCall += Run;
        }

        static void Run()
        {
            if (EditorApplication.isCompiling || EditorApplication.isUpdating || EditorApplication.isPlayingOrWillChangePlaymode)
            {
                EditorApplication.delayCall += Run;
                return;
            }
            SessionState.SetBool(SessionKey, true);
            // With the global cache on, locked shaders belong in CacheRoot
            if (Config.Instance.useGlobalLockedShaderCache) return;
            try
            {
                if (LockedShaderCache.HasEntriesToMove()) LockedShaderCache.MoveEntriesBesideMaterials();
            }
            catch (Exception e)
            {
                Debug.LogException(e);
            }
        }
    }

    static class LockedShaderCacheMenu
    {
        const string MenuRoot = "Poi/Thry/ThryEditor/Optimized Shader Cache/";

        static string DescribeCache()
        {
            long sizeBytes;
            int entryCount;
            LockedShaderCache.GetCacheStats(out sizeBytes, out entryCount);
            return entryCount + " locked shader" + (entryCount == 1 ? "" : "s") + ", "
                + (sizeBytes / (1024f * 1024f)).ToString("0.0") + " MB";
        }

        [MenuItem(MenuRoot + "Remove Unused", priority = 50)]
        static void RemoveUnused()
        {
            if (!EditorUtility.DisplayDialog("Optimized Shader Cache",
                    "Delete locked shaders that no material uses any more?\n\nCurrently " + DescribeCache()
                    + ".\n\nMaterials that are still locked keep their shaders and are unaffected.",
                    "Remove Unused", "Cancel"))
                return;

            int deleted = LockedShaderCache.CollectGarbage(includeFolders: true);
            EditorUtility.DisplayDialog("Optimized Shader Cache",
                deleted == 0
                    ? "Nothing to remove - every locked shader is still in use."
                    : "Removed " + deleted + " unused locked shader" + (deleted == 1 ? "" : "s") + ".\n\nNow " + DescribeCache() + ".",
                "OK");
        }

        [MenuItem(MenuRoot + "Clear All", priority = 51)]
        static void ClearAll()
        {
            if (!EditorUtility.DisplayDialog("Optimized Shader Cache",
                    "Delete the entire cache (" + DescribeCache() + ")?\n\n"
                    + "Locked materials get unlocked so they keep rendering. They lock again "
                    + "on upload, or from Poi > Thry > Material Lock Manager.",
                    "Clear All", "Cancel"))
                return;

            LockedShaderCache.Clear();
            AssetDatabase.Refresh();

            LockedShaderRecovery.RecoverAll(showProgress: true);
        }
    }
